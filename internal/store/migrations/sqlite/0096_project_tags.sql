--
-- 标签只回答「这个项目属于哪一类」,不参与权限、不参与流水线;用它筛项目是看的人
-- 在项目页本地过滤(项目列表本来就全量取回),所以存成 JSON 数组即可,不必拆关联表:
-- 单表一行一次读写,项目被删时也不留孤儿行。
--
--   tags_json : 去重后的标签数组(JSON);无标签为 '[]'
--
-- 顺序就是用户添加的顺序,筛选下拉按字母序另排;去重按不区分大小写(保留先出现的写法)。

