-- 0074 cert_remind_at:证书表补「上次为这张证书发过到期 / 续期失败提醒的时刻」。
--
-- 为什么要有这一列:到期扫描器每轮都会重新看一遍全部证书,而一张剩 29 天的证书会在
-- 整个 30 天续期窗口里被反复扫到 —— 没有节流状态就是每天几十条重复通知,用户只会把
-- 证书通知整体关掉。用 7 天窗口限流,一张证书在续期窗口里最多被提醒 4 次。
--
-- 为什么不复用 checked_at:那是「上次看过」,每轮扫描都会刷新,拿它当「上次说过」等于
-- 第一遍之后永远不再提醒。为什么也不靠进程内存:重启即失忆,升级一次就轰炸一遍。
--
-- 默认空串 = 从没提醒过,首次进入窗口当轮就发。仅 ADD COLUMN,不重建表。
ALTER TABLE certificates ADD COLUMN remind_at TEXT NOT NULL DEFAULT '';
